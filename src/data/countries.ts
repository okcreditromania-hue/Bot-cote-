export const COUNTRIES_LIST = Object.values(SUPPORTED_COUNTRIES);

export function resolveCountryCode(countryValue?: string): CountryCode {
  const val = (countryValue || '').trim().toUpperCase();
  if (val in SUPPORTED_COUNTRIES) return val as CountryCode;
  const lower = (countryValue || '').toLowerCase();
  if (lower.includes('ivoire')) return 'CI';
  if (lower.includes('burkina')) return 'BF';
  if (lower.includes('bissau')) return 'GW';
  if (lower.includes('mali')) return 'ML';
  if (lower.includes('niger')) return 'NE';
  if (lower.includes('sén') || lower.includes('sen')) return 'SN';
  if (lower.includes('togo')) return 'TG';
  return 'BJ';
}
